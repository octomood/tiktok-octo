'use strict';

const { test, expect } = require('@playwright/test');
const { extract, unwrap } = require('../scripts/release-notes');

/**
 * Сборка заметок к релизу из CHANGELOG.md без мягких переносов строк.
 */

test('extract склеивает перенесённые строки пунктов и абзацев, сохраняя блоки', () => {
  const source = [
    '# Changelog',
    '',
    '## 2.0.1',
    '',
    '### Добавлено',
    '',
    '- **Фича** — длинное описание,',
    '  которое перенесено',
    '  на несколько строк.',
    '  - Вложенный пункт',
    '    с продолжением.',
    '',
    'Обычный абзац',
    'из двух строк.',
    '',
    '```bash',
    'npm run lint',
    'npm test',
    '```',
    '',
    '## 2.0.0',
    '',
    '- Старая запись',
  ].join('\n');

  expect(extract('2.0.1', source)).toBe(
    [
      '### Добавлено',
      '',
      '- **Фича** — длинное описание, которое перенесено на несколько строк.',
      '  - Вложенный пункт с продолжением.',
      '',
      'Обычный абзац из двух строк.',
      '',
      '```bash',
      'npm run lint',
      'npm test',
      '```',
    ].join('\n'),
  );

  expect(unwrap('### Заголовок\n\n- Раз\n  два')).toBe('### Заголовок\n\n- Раз два');
  expect(extract('9.9.9', source)).toBeNull();
});
